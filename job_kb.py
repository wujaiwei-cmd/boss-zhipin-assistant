def role_for_title(title, jd_text=''):
    """根据职位名称（优先）和 JD 文本判断岗位大类。"""
    t = (title or '').lower()
    best, best_score = ROLE_INDEX['通用/其他'], 0
    for role in ROLES:
        score = 0
        for a in role['alias']:
            if a and a.lower() in t:
                # 名称越长越可信，避免"运营"命中"数据运营"时压过"数据分析"
                score = max(score, len(a))
        if score > best_score:
            best, best_score = role, score
    if best_score:
        return best

    # 标题没命中，用 JD 里的技能词投票
    from job_analysis import find_skills  # 延迟导入，避免循环依赖
    hits = set(find_skills(jd_text))
    best_score = 0
    for role in ROLES:
        if role['name'] == '通用/其他':
            continue
        score = len(hits & set(role['core'])) * 2 + len(hits & set(role['bonus']))
        if score > best_score:
            best, best_score = role, score
    return best
